	private static final int[] DELTA = new int[1155];                   // passo su k per residuo r = pf mod 1155
	private static final int[] NEXT = new int[1155];                    // residuo successivo
	private static final BigInteger[] DELTA_BASE = new BigInteger[1155]; // DELTA * 2^14

	static {
		long baseMod = base.mod(B1155).longValue();
		for (int r = 0; r < 1155; r++) {
			int d = phaseMap.get(BigInteger.valueOf(r)).intValue();
			DELTA[r] = d;
			NEXT[r] = (int) ((r + d * baseMod) % 1155);
			DELTA_BASE[r] = BigInteger.valueOf(d).multiply(base);
		}
	}
	

	public static void searchDivisorsC12(int n, int m) {

		System.out.println("START N16: " + n + "  (m = " + m + ")");
		long t0 = System.nanoTime();

		try {

			// percorso portabile (prima era "filesN14\\" + n: su Linux il backslash fa parte del nome)
			File f = new File("filesN16", n + ".txt");
			
			List<BigInteger[]> righe = new ArrayList<>(); // {kInizio, kInizioMax}
			
			try (FileReader fr = new FileReader(f); BufferedReader br = new BufferedReader(fr)) {
				String linea;
				while ((linea = br.readLine()) != null) {
					String[] parti = linea.split(";");
					righe.add(new BigInteger[] { new BigInteger(parti[0]), new BigInteger(parti[1]) });
				}
			}
			
			// Ogni riga e' indipendente dalle altre: le processiamo in parallelo,
			// una per core disponibile.
			int nThread = Runtime.getRuntime().availableProcessors();
			ExecutorService pool = Executors.newFixedThreadPool(nThread);
			
			TreeMap<BigInteger,BigInteger> mappa = new TreeMap<>();
			try {
				List<Future<BigInteger>> futures = new ArrayList<>();
				for (BigInteger[] riga : righe) {
					BigInteger kInizio = riga[0];
					futures.add(pool.submit(() -> avanza(kInizio, m)));
				}
				for (int i = 0; i < righe.size(); i++) {
					BigInteger kFinale = futures.get(i).get();
					mappa.put(kFinale, righe.get(i)[1]);
				}
			} finally {
				pool.shutdown();
			}
	
			try (FileWriter fw = new FileWriter(f); PrintWriter pw = new PrintWriter(fw)) {
				for (Entry<BigInteger, BigInteger> bEntry : mappa.entrySet()) {
					pw.println(bEntry.getKey() + ";" + bEntry.getValue());
				}
			}

			double sec = (System.nanoTime() - t0) / 1e9;
			long candidati = (long) righe.size() * m;
			System.out.printf("END N16: %d | righe: %d | passi/riga: %d | candidati: %,d | %.1f s | %,.0f candidati/s%n",
					n, righe.size(), m, candidati, sec, candidati / Math.max(sec, 1e-9));
			
		}
		catch(Exception e) {
			e.printStackTrace();
			failed = true;
		}


	}
	
	/**
	 * Fa m passi della ruota a partire da kInizio e restituisce il k raggiunto.
	 * Nessun break sul trovato (come da tua indicazione): se capita, si segnala e si continua.
	 */
	static BigInteger avanza(BigInteger kInizio, int m) {
		
		BigInteger pf = kInizio.multiply(base).add(BigInteger.ONE);
		int r = pf.mod(B1155).intValue();
		BigInteger k = kInizio;
		
		for (int i = 1; i <= m; i++) {
			
			if (superaFiltroF12(pf) && C12.mod(pf).signum() == 0) {
				segnalaTrovato(pf, k);
			}
			
			k = k.add(BigInteger.valueOf(DELTA[r]));
			pf = pf.add(DELTA_BASE[r]);
			r = NEXT[r];
		}
		
		return k;
	}
	
	/**
	 * Filtro veloce: n | F12 = 2^(2^12)+1  <=>  2^(2^12) == -1 (mod n).
	 * 12 quadrati modulari (2^12 = 4096 = 2^12, ci arrivi con 12 raddoppi dell'esponente)
	 * al posto della divisione di C12 (3763 bit) per pf: piu' veloce quanto piu' pf e' grande.
	 * Un "true" qui non basta a dichiarare trovato: si conferma sempre con C12.mod(pf).
	 */
	static boolean superaFiltroF12(BigInteger pf) {
		BigInteger x = BigInteger.valueOf(2);
		for (int i = 0; i < 12; i++) {
			x = x.multiply(x).mod(pf);
		}
		return x.equals(pf.subtract(BigInteger.ONE));
	}
	
